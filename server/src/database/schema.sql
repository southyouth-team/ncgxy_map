-- 三维场景文档：仅保存三维表现参数，平面几何仍由 campus_feature 唯一维护。
ALTER TABLE campus_feature
  ADD CONSTRAINT uq_feature_id_scope UNIQUE (id,campus_id,map_id);

CREATE TABLE campus_scene (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id BIGINT NOT NULL,
  map_id BIGINT NOT NULL UNIQUE,
  schema_version INTEGER NOT NULL DEFAULT 2,
  document JSONB NOT NULL,
  revision BIGINT NOT NULL DEFAULT 1,
  created_by VARCHAR(128) NOT NULL,
  updated_by VARCHAR(128) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_scene_map_scope FOREIGN KEY (map_id) REFERENCES campus_map(id) ON DELETE CASCADE,
  CONSTRAINT fk_scene_campus_scope FOREIGN KEY (campus_id) REFERENCES campus(id) ON DELETE CASCADE,
  CONSTRAINT uq_scene_id_campus_map UNIQUE (id,campus_id,map_id)
);

CREATE TABLE campus_scene_feature (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id BIGINT NOT NULL,
  map_id BIGINT NOT NULL,
  scene_id BIGINT NOT NULL,
  feature_id BIGINT NOT NULL,
  scene_object_id VARCHAR(128) NOT NULL,
  object_type VARCHAR(30) NOT NULL CHECK (
    object_type IN ('building','road','terrain','water','vegetation','facility')
  ),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_scene_feature_scene FOREIGN KEY (scene_id,campus_id,map_id)
    REFERENCES campus_scene(id,campus_id,map_id) ON DELETE CASCADE,
  CONSTRAINT fk_scene_feature_feature FOREIGN KEY (feature_id,campus_id,map_id)
    REFERENCES campus_feature(id,campus_id,map_id) ON DELETE CASCADE,
  CONSTRAINT uq_scene_feature_binding UNIQUE (scene_id,feature_id),
  CONSTRAINT uq_scene_object_binding UNIQUE (scene_id,scene_object_id)
);
CREATE INDEX idx_scene_feature_map ON campus_scene_feature(campus_id,map_id,feature_id);
