-- PostgreSQL 16+ / PostGIS 3.4+
-- 首期 campus-local 为局部平面坐标，SRID=0；绝不能解释为经纬度或米制坐标。
CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE campus (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  description TEXT,
  address VARCHAR(255),
  status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','active','archived')),
  created_by VARCHAR(128) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE campus_member (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id BIGINT NOT NULL REFERENCES campus(id) ON DELETE CASCADE,
  user_id VARCHAR(128) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'viewer' CHECK (role IN ('owner','admin','editor','viewer')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (campus_id, user_id)
);
CREATE INDEX idx_campus_member_user ON campus_member(user_id);

CREATE TABLE campus_map (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id BIGINT NOT NULL REFERENCES campus(id) ON DELETE CASCADE,
  slug VARCHAR(80) NOT NULL,
  name VARCHAR(160) NOT NULL,
  description TEXT,
  coordinate_system VARCHAR(40) NOT NULL DEFAULT 'campus-local',
  coordinate_unit VARCHAR(20) NOT NULL DEFAULT 'pixel' CHECK (coordinate_unit IN ('pixel','meter','local-unit')),
  canvas_width NUMERIC(12,3) NOT NULL DEFAULT 640 CHECK (canvas_width > 0),
  canvas_height NUMERIC(12,3) NOT NULL DEFAULT 480 CHECK (canvas_height > 0),
  coordinate_config JSONB,
  status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','archived')),
  revision BIGINT NOT NULL DEFAULT 1,
  published_version_id BIGINT,
  created_by VARCHAR(128) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (campus_id, slug)
);
CREATE INDEX idx_map_campus_status ON campus_map(campus_id,status);

CREATE TABLE campus_layer (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id BIGINT NOT NULL REFERENCES campus(id) ON DELETE CASCADE,
  map_id BIGINT NOT NULL REFERENCES campus_map(id) ON DELETE CASCADE,
  layer_key VARCHAR(80) NOT NULL,
  name VARCHAR(120) NOT NULL,
  feature_type VARCHAR(30) NOT NULL CHECK (feature_type IN ('building','road','water','green','sports','boundary','poi','custom')),
  sort_order INTEGER NOT NULL DEFAULT 0,
  visible BOOLEAN NOT NULL DEFAULT true,
  locked BOOLEAN NOT NULL DEFAULT false,
  style JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (map_id,layer_key),
  UNIQUE (id,campus_id,map_id)
);
CREATE INDEX idx_layer_campus_map ON campus_layer(campus_id,map_id,sort_order);

CREATE TABLE campus_feature (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id BIGINT NOT NULL REFERENCES campus(id) ON DELETE CASCADE,
  map_id BIGINT NOT NULL REFERENCES campus_map(id) ON DELETE CASCADE,
  layer_id BIGINT NOT NULL,
  feature_key VARCHAR(100) NOT NULL,
  name VARCHAR(160),
  geometry geometry(Geometry,0) NOT NULL,
  properties JSONB NOT NULL DEFAULT '{}'::jsonb,
  revision BIGINT NOT NULL DEFAULT 1,
  created_by VARCHAR(128) NOT NULL,
  updated_by VARCHAR(128) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (map_id,feature_key),
  CONSTRAINT fk_feature_layer_scope FOREIGN KEY (layer_id,campus_id,map_id)
    REFERENCES campus_layer(id,campus_id,map_id) ON DELETE CASCADE,
  CONSTRAINT chk_feature_geometry_2d CHECK (ST_NDims(geometry) = 2)
);
CREATE INDEX idx_feature_campus_map_layer ON campus_feature(campus_id,map_id,layer_id);
CREATE INDEX idx_feature_geometry_gist ON campus_feature USING GIST(geometry);

CREATE TABLE campus_asset (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id BIGINT NOT NULL REFERENCES campus(id) ON DELETE CASCADE,
  map_id BIGINT REFERENCES campus_map(id) ON DELETE SET NULL,
  asset_type VARCHAR(30) NOT NULL CHECK (asset_type IN ('base-map','image','texture','model','document','project-archive','other')),
  storage_provider VARCHAR(40) NOT NULL,
  bucket_name VARCHAR(120),
  object_key VARCHAR(512) NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  mime_type VARCHAR(120) NOT NULL,
  file_size BIGINT NOT NULL CHECK (file_size >= 0),
  checksum_sha256 CHAR(64),
  metadata JSONB,
  uploaded_by VARCHAR(128) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (storage_provider,bucket_name,object_key)
);
CREATE INDEX idx_asset_campus_map ON campus_asset(campus_id,map_id,asset_type);

CREATE TABLE campus_version (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campus_id BIGINT NOT NULL REFERENCES campus(id) ON DELETE CASCADE,
  map_id BIGINT NOT NULL REFERENCES campus_map(id) ON DELETE CASCADE,
  version_number INTEGER NOT NULL,
  version_name VARCHAR(160),
  status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','superseded')),
  snapshot JSONB NOT NULL,
  change_summary VARCHAR(500),
  created_by VARCHAR(128) NOT NULL,
  published_by VARCHAR(128),
  published_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (map_id,version_number)
);
CREATE INDEX idx_version_campus_map ON campus_version(campus_id,map_id,created_at DESC);

ALTER TABLE campus_map
  ADD CONSTRAINT fk_map_published_version
  FOREIGN KEY (published_version_id) REFERENCES campus_version(id) ON DELETE SET NULL;

